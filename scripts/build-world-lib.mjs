#!/usr/bin/env node
/**
 * Ship the app's world code to the design prototype — `apps/web/src/world/*.ts` →
 * `design/prototype/world-lib.js`.
 *
 *   node scripts/build-world-lib.mjs            # write it
 *   node scripts/build-world-lib.mjs --check    # verify only, exit 1 on drift
 *
 * Why this exists: the prototype draws the same floor plan as the app, seats the same people and
 * moves its camera with the same maths, but it is a **plain script** — no bundler, no React. Rather
 * than write that logic twice (and let the two drift the first time someone fixes a bug in one),
 * the shared half is bundled from its single source and checked in, the same way the design tokens
 * and the owner's data are.
 *
 * The output is deliberately readable and unminified: it is a design artefact, and a reviewer should
 * be able to see what the browser is running. It is byte-compared by `--check`, so the file in the
 * repository is exactly what the build produces — and `esbuild` is pinned to an exact version in
 * `package.json`, so two machines produce the same bytes.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import vm from 'node:vm';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = join(REPO, 'apps', 'web', 'src', 'world', 'demo-entry.ts');
const OUT = join(REPO, 'design', 'prototype', 'world-lib.js');

const BANNER = `/* GENERATED — do not edit this file.
 *
 * The shared half of the world (camera maths, the owner's plan, the seating rule, the furniture
 * paths) lives once, in apps/web/src/world/*.ts, and is bundled here so the design prototype can
 * use the very same code instead of a copy.
 *
 * Rebuild:  node scripts/build-world-lib.mjs
 * Verify:   node scripts/build-world-lib.mjs --check     (the gate runs this)
 */`;

/** The bundle, as bytes. Deterministic for a given esbuild version and source. */
async function bundle() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'iife',
    globalName: 'WORLD_LIB',
    target: ['es2020'],
    platform: 'neutral',
    write: false,
    legalComments: 'none',
    banner: { js: BANNER },
    // Readable, not minified: this ships to a design prototype people read.
    minify: false,
    logLevel: 'warning',
  });
  return result.outputFiles[0].text;
}

/**
 * Everything `design/prototype/world.js` is allowed to reach for. Checked by evaluating the bundle
 * rather than by trusting the source: esbuild drops an export that does not exist with a warning,
 * and this was written because exactly that happened once — `defaultPlan` was listed in the entry
 * file, missing from its module, and the plan simply failed to draw with `lib.defaultPlan is not a
 * function` in the console.
 */
const REQUIRED = [
  'DEFAULT_LAYOUT', 'WORLD', 'EASE', 'LADDER', 'MAX_SCALE', 'MIN_SCALE',
  'PROP_GRID', 'PROP_PATHS',
  'cameraTransform', 'centreOn', 'clampCamera', 'clampScale', 'defaultPlan', 'ease', 'fitCamera',
  'nextRung', 'panBy', 'roomAt', 'seatAgents', 'shapeFor', 'sprite', 'toPlan', 'toScreen',
  'wheelFactor', 'zoomAbout', 'zoomBy', 'zoomByCentre',
];

function missingExports(text) {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(text, sandbox);
  const lib = sandbox.WORLD_LIB || {};
  return REQUIRED.filter((name) => lib[name] === undefined);
}

async function main() {
  const text = await bundle();
  const check = process.argv.includes('--check');
  const missing = missingExports(text);
  if (missing.length) {
    console.error(`world-lib: the bundle is missing ${missing.join(', ')} — the prototype reaches for it.`);
    process.exit(1);
  }

  if (check) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
    if (current === null) {
      console.error(`world-lib: missing — run node scripts/build-world-lib.mjs`);
      process.exit(1);
    }
    if (current !== text) {
      console.error('world-lib: out of date — apps/web/src/world changed. Rebuild: node scripts/build-world-lib.mjs');
      process.exit(1);
    }
    console.log(`world-lib: in sync with the app's world code — ${(text.length / 1024).toFixed(1)} KB`);
    return;
  }

  writeFileSync(OUT, text);
  console.log(`world-lib: wrote ${relative(REPO, OUT)} — ${(text.length / 1024).toFixed(1)} KB`);
}

await main();
